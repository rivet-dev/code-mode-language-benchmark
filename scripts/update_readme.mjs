// Rewrites the results section of README.md, between <!-- results:start --> and
// <!-- results:end -->, from results/*.json: one table with every runtime and metric, then the
// charts. Everything outside the markers is left as written.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const README = path.join(ROOT, "README.md");
const RESULTS = path.join(ROOT, "results");
const START = "<!-- results:start -->";
const END = "<!-- results:end -->";
const KIB = 1024;
const MIB = 1024 * 1024;
const GROUPS = ["embedded", "process"];

/** Three significant digits, written without exponent notation. */
const sig = (value) => String(Number(value.toPrecision(3)));

function formatBytes(bytes) {
	return bytes < MIB ? `${sig(bytes / KIB)} KiB` : `${sig(bytes / MIB)} MiB`;
}

function formatMs(ms) {
	if (ms < 1) return `${sig(ms * 1e3)} µs`;
	if (ms >= 1000) return `${sig(ms / 1e3)} s`;
	return `${sig(ms)} ms`;
}

function formatUs(us) {
	return us >= 1000 ? `${sig(us / 1e3)} ms` : `${sig(us)} µs`;
}

const formatCount = (count) => count.toLocaleString("en-US");
const orNA = (value, format) => (value === null ? "n/a" : format(value));

function runsAs(result) {
	if (result.group === "process") return "separate process";
	return `embedded in ${result.host.split(" ")[0]}`;
}

function pacific(iso, options) {
	return new Intl.DateTimeFormat("en-US", { timeZone: "America/Los_Angeles", ...options }).format(new Date(iso));
}

function loadResults() {
	const results = fs.readdirSync(RESULTS)
		.filter((file) => file.endsWith(".json"))
		.map((file) => JSON.parse(fs.readFileSync(path.join(RESULTS, file), "utf8")));
	for (const result of results) {
		for (const field of ["runtime", "label", "language", "group", "host", "version", "metrics", "notes", "measuredAt", "loadAverage"]) {
			if (!(field in result)) throw new Error(`results/${result.runtime}.json has no ${field}`);
		}
	}
	return results.sort((first, second) => {
		const byGroup = GROUPS.indexOf(first.group) - GROUPS.indexOf(second.group);
		if (byGroup !== 0) return byGroup;
		return (first.metrics.memoryBytes ?? Infinity) - (second.metrics.memoryBytes ?? Infinity);
	});
}

/** One sentence on when and where the numbers were measured. */
function environmentLine(results) {
	const times = results.map((result) => result.measuredAt).sort();
	const loads = results.flatMap((result) => [result.loadAverage.start[0], result.loadAverage.end[0]]);
	const day = pacific(times[0], { month: "long", day: "numeric", year: "numeric" });
	const lastDay = pacific(times.at(-1), { month: "long", day: "numeric", year: "numeric" });
	const time = (iso) => pacific(iso, { hour: "numeric", minute: "2-digit" });
	const zone = pacific(times.at(-1), { timeZoneName: "short" }).split(" ").at(-1);
	const when = day === lastDay
		? `on ${day}, between ${time(times[0])} and ${time(times.at(-1))} ${zone}`
		: `between ${day} and ${lastDay}`;
	let where = "";
	const environmentPath = path.join(RESULTS, "raw/environment.json");
	if (fs.existsSync(environmentPath)) {
		const { host } = JSON.parse(fs.readFileSync(environmentPath, "utf8"));
		where = ` on ${host.cpu} with ${host.logicalCores} logical cores (${host.os}, kernel ${host.kernel})`;
	}
	const load = `The 1-minute load average ran from ${Math.min(...loads).toFixed(1)} to ${Math.max(...loads).toFixed(1)} during the measurements.`;
	return `Measured ${when}${where}. ${load}`;
}

function table(results) {
	const rows = [
		"| Runtime | Language | Runs as | Base memory | Instances per GiB | Time to first response | Tool call round trip | Parse and aggregate 3 MB of JSON |",
		"| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
	];
	for (const result of results) {
		const { memoryBytes, startMs, toolCallUs, computeMs, instancesPerGiB } = result.metrics;
		rows.push(`| ${result.label} | ${result.language} | ${runsAs(result)} | ${orNA(memoryBytes, formatBytes)} | ${orNA(instancesPerGiB, formatCount)} | ${orNA(startMs, formatMs)} | ${orNA(toolCallUs, formatUs)} | ${orNA(computeMs, formatMs)} |`);
	}
	return rows.join("\n");
}

function section(results) {
	const charts = [
		["metric-memory.png", "Base memory per invocation"],
		["metric-density.png", "Instances per GiB"],
		["metric-start.png", "Time to first response"],
		["metric-tool-call.png", "Tool call round trip"],
		["metric-compute.png", "Parse and aggregate 3 MB of JSON"],
	];
	return [
		START,
		"<!-- Generated by scripts/update_readme.mjs from results/*.json. Edits here are overwritten. -->",
		"",
		environmentLine(results),
		"",
		table(results),
		"",
		"Embedded rows come first, then separate processes, each sorted by base memory. Lower is better in every column except instances per GiB. n/a marks a metric that was not measured for that runtime; its results file says why. Each `results/<runtime>.json` also carries notes with secondary numbers (private and proportional memory, CPU per call, batch medians), and `results/raw/` holds every harness's own output.",
		"",
		"The charts cover thirteen runtimes: Lua, LuaJIT, QuickJS, V8, MicroPython and Pyodide embedded, and dash, bash, CPython (spawned and forked), Node, Bun and Deno as processes. The Lua process rows and the Rust-hosted engines appear only in the table.",
		"",
		"![Base memory, time to first response and tool call round trip for each charted runtime](charts/combined.png)",
		"",
		"![Base memory against time to first response, both on log scales](charts/scatter.png)",
		"",
		"<p>",
		...charts.map(([file, alt]) => `<img src="charts/${file}" width="49%" alt="${alt}">`),
		"</p>",
		END,
	].join("\n");
}

const readme = fs.readFileSync(README, "utf8");
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start < 0 || end < start) throw new Error(`README.md needs ${START} and ${END} markers`);
const results = loadResults();
if (results.length === 0) throw new Error("results/ is empty; run npm run bench first");
fs.writeFileSync(README, readme.slice(0, start) + section(results) + readme.slice(end + END.length));
console.error(`[readme] wrote ${results.length} runtimes into README.md`);
